import { chromium } from 'playwright-core';
import { loadConfig } from '../../apps/server/src/config';
import { startServer } from '../../apps/server/src/server';
import { TestClient } from '../integration/wsClient';
const mod: any = await import('@sparticuz/chromium');
const srv = await startServer(loadConfig({ port: 0, host: '127.0.0.1', serveStatic: true, staticDir: 'apps/web/dist' }), { countdownMs: 500, tickMs: 50, now: Date.now });
const host = await TestClient.connect(srv.port);
host.send({ t: 'host:create', v: 1 });
const { code } = await host.waitFor('host:created');
const other = await TestClient.connect(srv.port);
other.send({ t: 'player:join', v: 1, code, name: 'Bot', character: 'kai' });
const b = await chromium.launch({ executablePath: await mod.default.executablePath(), args: mod.default.args.filter((a: string) => !a.startsWith('--single-process')) });
const ctx = await b.newContext({ viewport: { width: 844, height: 390 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
const p = await ctx.newPage();
p.on('console', (m) => console.log('console', m.type(), m.text()));
await p.goto(`http://127.0.0.1:${srv.port}/controller.html?room=${code}`);
await p.locator('input[aria-label="El teu nom"]').fill('A');
await p.getByRole('button', { name: 'Triar xef' }).click();
await p.getByRole('button', { name: 'Entrar a la sala' }).click();
await p.locator('.me-card').waitFor();
host.send({ t: 'flow', action: 'start' });
await p.locator('.gamepad').waitFor();
await new Promise((r) => setTimeout(r, 1000));
await p.evaluate(() => { document.querySelector('.stick-zone')!.addEventListener('pointerdown', (e) => console.log('PD', (e as PointerEvent).pointerType)); document.querySelector('.stick-zone')!.addEventListener('pointermove', () => console.log('PM')); });
const bb = (await p.locator('.stick-zone').boundingBox())!;
console.log('box', bb);
const cx = bb.x + bb.width / 2, cy = bb.y + bb.height / 2;
await p.mouse.move(cx, cy); await p.mouse.down(); await p.mouse.move(cx + 60, cy, { steps: 3 });
console.log('input', await p.evaluate(() => (window as any).__pad.input));
await new Promise((r) => setTimeout(r, 600));
console.log(srv.rooms.get(code)!.debugSim()!.playerViews().map((v) => [v.x, v.z]));
await p.mouse.up();
// try touch
await p.touchscreen.tap(cx, cy);
const el = await p.evaluate(({x,y}) => document.elementFromPoint(x, y)?.className, { x: cx, y: cy });
console.log('element at center', el);
await b.close(); await srv.close(); process.exit(0);
