/** Tiny DOM helpers (no framework: menus are simple and the 3D canvas owns the frame budget). */
export type Child = Node | string | number | null | undefined | false;

export function h<K extends keyof HTMLElementTagNameMap>(
  tag: K,
  attrs: Record<string, unknown> = {},
  ...children: (Child | Child[])[]
): HTMLElementTagNameMap[K] {
  const el = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs)) {
    if (v === undefined || v === null || v === false) continue;
    if (k === 'class') el.className = String(v);
    else if (k === 'style' && typeof v === 'object') {
      for (const [prop, val] of Object.entries(v as Record<string, string>)) {
        // custom properties (--x) only work through setProperty
        if (prop.startsWith('--')) el.style.setProperty(prop, String(val));
        else (el.style as unknown as Record<string, string>)[prop] = String(val);
      }
    }
    else if (k === 'html') el.innerHTML = String(v);
    else if (k.startsWith('on') && typeof v === 'function') el.addEventListener(k.slice(2).toLowerCase(), v as EventListener);
    else if (k === 'dataset' && typeof v === 'object') Object.assign(el.dataset, v);
    else el.setAttribute(k, v === true ? '' : String(v));
  }
  for (const c of children.flat()) {
    if (c === null || c === undefined || c === false) continue;
    el.append(c instanceof Node ? c : document.createTextNode(String(c)));
  }
  return el;
}

/** Element from trusted static SVG/HTML markup generated by our own code. */
export function svg(markup: string): HTMLElement {
  const t = document.createElement('template');
  t.innerHTML = markup.trim();
  return t.content.firstElementChild as HTMLElement;
}

export function fmtTime(s: number): string {
  const v = Math.max(0, Math.ceil(s));
  return `${Math.floor(v / 60)}:${String(v % 60).padStart(2, '0')}`;
}

export function store<T>(key: string, fallback: T, storage: Storage = localStorage): { get: () => T; set: (v: T) => void; clear: () => void } {
  return {
    get: () => {
      try {
        const raw = storage.getItem(key);
        return raw ? (JSON.parse(raw) as T) : fallback;
      } catch {
        return fallback;
      }
    },
    set: (v) => {
      try {
        storage.setItem(key, JSON.stringify(v));
      } catch {
        /* storage full / disabled: non-critical */
      }
    },
    clear: () => {
      try {
        storage.removeItem(key);
      } catch {
        /* ignore */
      }
    },
  };
}
